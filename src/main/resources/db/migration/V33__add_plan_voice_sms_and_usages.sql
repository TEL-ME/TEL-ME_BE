-- 요금제별 통화(분)·문자(건) 제공량. 값은 docs/POLICY.md PLAN-07과 같아야 한다
-- 데이터(is_unlimited)와 같은 방식으로 무제한은 NULL 대신 플래그로 구분한다
ALTER TABLE plans
    ADD COLUMN voice_minutes      INT,
    ADD COLUMN sms_count          INT,
    ADD COLUMN is_voice_unlimited BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN is_sms_unlimited   BOOLEAN NOT NULL DEFAULT FALSE;

-- 기존 15행을 먼저 채우고 제약을 건다. 값이 NULL이면 무제한
UPDATE plans p
   SET voice_minutes      = v.voice,
       sms_count          = v.sms,
       is_voice_unlimited = v.voice IS NULL,
       is_sms_unlimited   = v.sms IS NULL
  FROM (VALUES
        ('FIVE_G_UNLIMITED', NULL::INT, NULL::INT),
        ('FIVE_G_PREMIUM',   NULL,      NULL),
        ('FIVE_G_STANDARD',  NULL,      NULL),
        ('FIVE_G_LITE',      NULL,      NULL),
        ('LTE_MAX',          NULL,      NULL),
        ('LTE_PLUS',         NULL,      NULL),
        ('LTE_BASIC',        700,       NULL),
        ('BUDGET_SAVE',      500,       300),
        ('BUDGET_MINI',      300,       100),
        ('FIVE_G_YOUTH',     NULL,      NULL),
        ('LTE_YOUTH',        1000,      NULL),
        ('BUDGET_YOUTH',     300,       NULL),
        ('FIVE_G_SENIOR',    NULL,      NULL),
        ('LTE_SENIOR',       NULL,      300),
        ('BUDGET_SENIOR',    700,       100)
       ) AS v(code, voice, sms)
 WHERE p.code = v.code;

ALTER TABLE plans
    ADD CONSTRAINT ck_plans_voice CHECK (
        (is_voice_unlimited AND voice_minutes IS NULL) OR
        (NOT is_voice_unlimited AND voice_minutes IS NOT NULL AND voice_minutes > 0)
    ),
    ADD CONSTRAINT ck_plans_sms CHECK (
        (is_sms_unlimited AND sms_count IS NULL) OR
        (NOT is_sms_unlimited AND sms_count IS NOT NULL AND sms_count > 0)
    );

-- 월별 사용량. 실제 통신망이 없어 서비스가 사용자별로 생성한 값을 저장해 고정한다
-- usage_month는 해당 월의 1일(KST)이고, 이번 달 값도 월 전체 기준으로 저장한다
CREATE TABLE subscription_usages (
    usage_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id    BIGINT      NOT NULL REFERENCES user_subscriptions (subscription_id),
    usage_month        DATE        NOT NULL,
    used_data_mb       BIGINT      NOT NULL,
    used_voice_minutes INT         NOT NULL,
    used_sms_count     INT         NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_subscription_usages_month UNIQUE (subscription_id, usage_month),
    CONSTRAINT ck_subscription_usages_month CHECK (EXTRACT(DAY FROM usage_month) = 1),
    CONSTRAINT ck_subscription_usages_amount CHECK (
        used_data_mb >= 0 AND used_voice_minutes >= 0 AND used_sms_count >= 0
    )
);
