-- 품질
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE message_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id  BIGINT      NOT NULL REFERENCES chat_messages (message_id) ON DELETE CASCADE,
    user_id     BIGINT      REFERENCES users (user_id),
    guest_id    UUID        REFERENCES guests (guest_id),
    rating      VARCHAR(10) NOT NULL,               -- LIKE / DISLIKE
    reason_code VARCHAR(30),                        -- WRONG_INFO / NOT_RELATED / HARD_TO_READ
    comment     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 부분 유니크 인덱스(아래)와 함께 JPA로는 표현이 안 되므로 서비스 레이어에서도 검증해야 한다.
    CONSTRAINT ck_feedback_actor CHECK (user_id IS NOT NULL OR guest_id IS NOT NULL)
);

CREATE TRIGGER trg_message_feedback_updated_at
    BEFORE UPDATE ON message_feedback
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- 메시지당 회원 1건 / 게스트 1건. NULL이 섞여 복합 UNIQUE가 안 되므로 부분 인덱스로 처리한다.
CREATE UNIQUE INDEX uk_feedback_user
    ON message_feedback (message_id, user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uk_feedback_guest
    ON message_feedback (message_id, guest_id) WHERE guest_id IS NOT NULL;

-- ─────────────────────────────────────────────────────────────────────
-- 매장
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE stores (
    store_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    phone       VARCHAR(20),
    address     VARCHAR(255)  NOT NULL,             -- 지도 실패 시 텍스트 대체
    region_code VARCHAR(20),                        -- 위치 권한 거부 시 지역 검색용
    latitude    NUMERIC(9, 6) NOT NULL,
    longitude   NUMERIC(9, 6) NOT NULL,
    status      VARCHAR(20)   NOT NULL DEFAULT 'OPEN', -- OPEN / CLOSED_DOWN
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_stores_updated_at
    BEFORE UPDATE ON stores
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TABLE store_service_types (
    service_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(40) NOT NULL UNIQUE,    -- NEW_LINE / PORT_IN / NAME_CHANGE / USIM_REISSUE
    name            VARCHAR(50) NOT NULL
);

CREATE TABLE store_services (
    store_id        BIGINT NOT NULL REFERENCES stores (store_id) ON DELETE CASCADE,
    service_type_id BIGINT NOT NULL REFERENCES store_service_types (service_type_id),
    PRIMARY KEY (store_id, service_type_id)
);

CREATE TABLE store_hours (
    store_id    BIGINT   NOT NULL REFERENCES stores (store_id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL,                  -- 1(월) ~ 7(일)
    open_time   TIME,
    close_time  TIME,
    is_closed   BOOLEAN  NOT NULL DEFAULT false,
    PRIMARY KEY (store_id, day_of_week)
);

-- ─────────────────────────────────────────────────────────────────────
-- 인덱스
-- ─────────────────────────────────────────────────────────────────────
-- ERD "인덱스" 섹션의 10개 + 벡터 검색용 HNSW.
-- FK 컬럼 인덱스는 여기에 없다. PostgreSQL은 FK를 걸어도 자식 쪽 인덱스를 자동 생성하지
-- 않으므로, 필요한 것은 각 기능 담당자가 실제 쿼리를 보고 추가한다.
CREATE INDEX idx_session_user      ON chat_sessions (user_id, last_active_at DESC);
CREATE INDEX idx_session_guest     ON chat_sessions (guest_id);
CREATE INDEX idx_guest_expires     ON guests (expires_at) WHERE merged_user_id IS NULL;
CREATE INDEX idx_execution_session ON chat_executions (session_id, started_at DESC);
CREATE INDEX idx_request_pending   ON consult_requests (session_id, status);
CREATE INDEX idx_generation_exec   ON llm_generations (execution_id);
CREATE INDEX idx_source_message    ON message_sources (message_id);
CREATE INDEX idx_faq_category      ON faqs (category) WHERE status = 'ACTIVE';
CREATE INDEX idx_embed_sync        ON faq_embeddings (sync_status) WHERE sync_status <> 'SYNCED';
CREATE INDEX idx_store_service     ON store_services (service_type_id, store_id);

-- HNSW: ivfflat과 달리 인덱스 생성 시 리스트 개수 튜닝/재학습이 필요 없어 FAQ 규모(수천~수만 건)에는
-- 운영 부담이 적다. bge-m3 임베딩은 코사인 유사도 기준으로 비교하므로 vector_cosine_ops를 사용한다.
-- 이 인덱스가 없으면 유사도 검색이 전건 순차 스캔이 된다.
CREATE INDEX idx_faq_embeddings_embedding ON faq_embeddings
    USING hnsw (embedding vector_cosine_ops);
