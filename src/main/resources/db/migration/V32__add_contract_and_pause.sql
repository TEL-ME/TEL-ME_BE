-- 약정. 요금제 가입 때 선택하며 약정 개월 수와 가입 당시 할인율을 함께 저장한다(둘 다 NULL이면 약정 없음)
-- 할인율을 구독에 남겨 두므로 이후 정책 값이 바뀌어도 이미 가입한 약정의 위약금 계산은 그대로다
ALTER TABLE user_subscriptions
    ADD COLUMN contract_months            INT,
    ADD COLUMN contract_discount_percent  INT,
    ADD CONSTRAINT ck_subscriptions_contract CHECK (
        (contract_months IS NULL AND contract_discount_percent IS NULL) OR
        (contract_months IS NOT NULL AND contract_discount_percent IS NOT NULL
            AND contract_months > 0 AND contract_discount_percent BETWEEN 1 AND 100)
    );

-- 해지 때 확정한 위약금(원). 해지 이력에만 남긴다
ALTER TABLE subscription_histories
    ADD COLUMN penalty_amount BIGINT,
    ADD CONSTRAINT ck_subscription_histories_penalty CHECK (
        penalty_amount IS NULL OR (type = 'CANCEL' AND penalty_amount >= 0)
    );

-- 일시 정지. ends_at은 신청 때 정한 종료 예정이고 해제하면 해제 시각으로 당긴다
-- 기간이 지나면 조회 시점에 정지가 끝난 것으로 계산하므로 별도 종료 처리 없이 행을 그대로 둔다
-- 1회 30일, 연 90일, 중복 정지 불가는 서비스가 구독 행 잠금 아래에서 확인한다
CREATE TABLE subscription_pauses (
    pause_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT      NOT NULL REFERENCES user_subscriptions (subscription_id),
    started_at      TIMESTAMPTZ NOT NULL,
    ends_at         TIMESTAMPTZ NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_subscription_pauses_period CHECK (ends_at >= started_at)
);

CREATE INDEX ix_subscription_pauses_subscription
    ON subscription_pauses (subscription_id, started_at DESC);
