-- 요금제 가입. 청소년·시니어 요금제 자격(만 나이) 확인용 생년월일은 요금제 가입 때 받아 저장하므로 기존 회원은 NULL이다
ALTER TABLE users
    ADD COLUMN birth_date DATE;

-- 가입 상태. 현재 요금제는 여기 두지 않고 subscription_histories에서 계산한다
-- 해지 후 재가입은 새 행이라 한 사용자의 행이 여러 개일 수 있고, 활성 구독은 하나뿐이다
CREATE TABLE user_subscriptions (
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (user_id),
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / CANCELED
    subscribed_at   TIMESTAMPTZ NOT NULL,           -- 가입 당월에는 요금제를 바꿀 수 없다
    canceled_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'CANCELED')),
    CONSTRAINT ck_subscriptions_canceled CHECK ((status = 'CANCELED') = (canceled_at IS NOT NULL))
);

CREATE UNIQUE INDEX uk_subscriptions_active_user
    ON user_subscriptions (user_id) WHERE status = 'ACTIVE';

CREATE TRIGGER trg_user_subscriptions_updated_at
    BEFORE UPDATE ON user_subscriptions
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- 가입·변경·해지 이력. 변경은 신청 다음 날 0시부터 적용되므로 신청 시각(created_at)과 적용 시작(effective_from)을 따로 둔다
-- 현재 요금제는 effective_from이 지난 가장 최근 가입·변경의 to_plan_id이고, 아직 안 지난 변경은 예약된 변경이다
CREATE TABLE subscription_histories (
    history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT      NOT NULL REFERENCES user_subscriptions (subscription_id),
    type            VARCHAR(20) NOT NULL,           -- SUBSCRIBE / CHANGE / CANCEL
    from_plan_id    BIGINT REFERENCES plans (plan_id), -- 가입이면 NULL, 해지면 해지 당시 요금제
    to_plan_id      BIGINT REFERENCES plans (plan_id), -- 해지면 NULL
    effective_from  TIMESTAMPTZ NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_subscription_histories_type CHECK (type IN ('SUBSCRIBE', 'CHANGE', 'CANCEL')),
    CONSTRAINT ck_subscription_histories_plans CHECK (
        (type = 'SUBSCRIBE' AND from_plan_id IS NULL AND to_plan_id IS NOT NULL) OR
        (type = 'CHANGE' AND from_plan_id IS NOT NULL AND to_plan_id IS NOT NULL AND from_plan_id <> to_plan_id) OR
        (type = 'CANCEL' AND from_plan_id IS NOT NULL AND to_plan_id IS NULL)
    )
);

CREATE INDEX ix_subscription_histories_subscription
    ON subscription_histories (subscription_id, effective_from DESC);
