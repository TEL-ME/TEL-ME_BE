-- 음성(TTS·STT) 서비스 전체의 하루 사용량. 서버 메모리 카운터는 재배포·재시작마다 0이 되고 서버가 여러 대면 대수만큼 한도가 늘어서 DB로 옮긴다
-- 하루(KST)·종류마다 한 행이라 하루에 2행만 쌓인다
CREATE TABLE speech_daily_usages (
    usage_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_date  DATE        NOT NULL,                -- 한국 시간 기준 날짜
    kind        VARCHAR(20) NOT NULL,                -- TTS_CHARACTERS(글자 수) / STT_SECONDS(초)
    used_amount BIGINT      NOT NULL DEFAULT 0,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 같은 날 같은 종류의 동시 차감이 한 행으로 모이게 하는 upsert의 충돌 기준
    CONSTRAINT uk_speech_daily_usages_date_kind UNIQUE (usage_date, kind),
    CONSTRAINT ck_speech_daily_usages_kind CHECK (kind IN ('TTS_CHARACTERS', 'STT_SECONDS')),
    CONSTRAINT ck_speech_daily_usages_amount CHECK (used_amount >= 0)
);
