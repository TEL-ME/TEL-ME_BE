-- data_gb는 기본 제공량(GB)이고, 무제한은 NULL 대신 is_unlimited로 구분한다
CREATE TABLE plans (
    plan_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(40)   NOT NULL UNIQUE,
    name         VARCHAR(50)   NOT NULL,
    network_type VARCHAR(20)   NOT NULL,                -- FIVE_G / LTE / BUDGET
    target_group VARCHAR(20)   NOT NULL DEFAULT 'GENERAL', -- GENERAL / YOUTH / SENIOR
    monthly_fee  INT           NOT NULL,                -- 원, 부가세 포함
    data_gb      NUMERIC(6, 1),
    is_unlimited BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order   INT           NOT NULL,
    status       VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / DISCONTINUED
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_plans_network_type CHECK (network_type IN ('FIVE_G', 'LTE', 'BUDGET')),
    CONSTRAINT ck_plans_target_group CHECK (target_group IN ('GENERAL', 'YOUTH', 'SENIOR')),
    CONSTRAINT ck_plans_status CHECK (status IN ('ACTIVE', 'DISCONTINUED')),
    CONSTRAINT ck_plans_monthly_fee CHECK (monthly_fee >= 0),
    CONSTRAINT ck_plans_data CHECK (
        (is_unlimited AND data_gb IS NULL) OR
        (NOT is_unlimited AND data_gb IS NOT NULL AND data_gb > 0)
    )
);

CREATE TRIGGER trg_plans_updated_at
    BEFORE UPDATE ON plans
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

