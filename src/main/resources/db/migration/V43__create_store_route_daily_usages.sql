-- 하루(KST)·경로 API별 호출 예약 수만 저장한다. 경로 응답·좌표는 저장하지 않는다.
CREATE TABLE store_route_daily_usages (
    usage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_date DATE NOT NULL,
    kind VARCHAR(20) NOT NULL,
    used_amount BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_store_route_daily_usages_date_kind UNIQUE (usage_date, kind),
    CONSTRAINT ck_store_route_daily_usages_kind CHECK (kind IN ('CAR', 'TRANSIT', 'WALK', 'BICYCLE')),
    CONSTRAINT ck_store_route_daily_usages_amount CHECK (used_amount >= 0)
);
