package com.telme.consult.service;

// 채팅에서 받는 요금제 업무 요청. 보안상 채팅에서 바로 처리하지 않고, 지금 상태에 맞는 안내와 처리 화면으로 가는 링크만 준다
public enum PlanTask {
    // 다른 요금제로 변경. 요금제 변경 화면으로 안내한다
    CHANGE,
    // 가입한 요금제가 없을 때 새로 신청. 요금제 가입 화면으로 안내한다
    SUBSCRIBE,
    // 일시 정지. 내 요금제 화면으로 안내한다
    PAUSE,
    // 해지. 위약금과 바로 끊기는 영향을 먼저 보여주고 내 요금제 화면으로 안내한다
    CANCEL
}
